X = []
for caracter in caracteres:
    pixeles = []
    for fila in caracter:
        bits_fila = format(fila, '05b')        # 0x0a -> '01010'
        pixeles += [int(b) for b in bits_fila] # '01010' -> [0,1,0,1,0]
    X.append(pixeles)
X = np.array(X, dtype='float32')
print("X:", X)
# Agregar ruido a los datos de entrada
probabilidad_ruido = 0.1  # Probabilidad de cambiar un píxel %10
def agregar_ruido(X, probabilidad_ruido):
    X_ruidoso = X.copy()
    for caracter in X_ruidoso:
        for i in range(len(caracter)):
            if np.random.rand() < probabilidad_ruido:
                caracter[i] = 1 - caracter[i]  # Cambiar el valor del píxel (0 -> 1, 1 -> 0)
    return X_ruidoso


# Modelo de autocodificador
# Codificador: 35 -> 20 -> 10
# Al tener 10 nodos en el espacio latente se pierde menos informacion y por lo tanto mejora la capacidad del modelo 
# para reconstruir los caracteres originales a partir de las entradas ruidosas.
nodos_entrada = layers.Input(shape=(35,))
x = layers.Dense(20, activation='tanh')(nodos_entrada) 
espacio_latente = layers.Dense(10, activation='tanh')(x) 

#Decodificador: 10 -> 20 -> 35
x = layers.Dense(20, activation='tanh')(espacio_latente)
nodos_salida = layers.Dense(35, activation='sigmoid')(x) 

#Creación autocodificador
autocodificador = models.Model(inputs=nodos_entrada, outputs=nodos_salida)
autocodificador.compile(optimizer=Adam(learning_rate=0.001), loss='mse')


# Agregar ruido a los datos de entrada
# 50 copias de cada dato de entrada con ruido(diferente) para entrenar el modelo
X_sin_ruido = []
X_con_ruido = []
for i in range(50):
    X_sin_ruido.append(X)
    X_con_ruido.append(agregar_ruido(X, probabilidad_ruido))
X_sin_ruido = np.concatenate(X_sin_ruido) # concatenate para que fit pueda recibir un array de 2 dimensiones
X_con_ruido = np.concatenate(X_con_ruido)


# Entrenamiento del modelo: entrada on ruido y espera salida sin ruido
autocodificador.fit(X_con_ruido, X_sin_ruido, epochs=300, batch_size=32, verbose=0) #300 epocas porque ya hay 50 copias de cada dato 


# Visualizacion del caracter original, con ruido y reconstruido
X_con_ruido_grafico = X_con_ruido[:len(X)] # primera de las 50 copias usadas en el entrenamiento
salidas_predichas = autocodificador.predict(X_con_ruido_grafico, verbose=0)
print("Pixeles mal por caracter: ", np.sum((salidas_predichas > 0.5) != X, axis=1))

