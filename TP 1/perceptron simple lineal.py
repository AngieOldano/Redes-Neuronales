import numpy as np
import random

entradas_crudas = np.loadtxt(r"TP1-ej2-Conjunto-entrenamiento.txt")
esperados = np.loadtxt(r"TP1-ej2-Salida-deseada.txt")

# sesgo/umbral (w0)
unos = np.ones((entradas_crudas.shape[0], 1))
entradas = np.hstack((entradas_crudas, unos))

print(f'entradas: {entradas}')

i = 0
w = np.array([0.0, 0.0, 0.0, 0.0]) # 3 características + 1 umbral
error_min = float('inf')
w_min = w.copy()

COTA = 50000
eta = 0.0001

def f_activacion(h):
    return h

def calcularError(esperados, entradas, pesos):
    error = 0
    for idx in range(len(entradas)):
        h = entradas[idx] @ pesos
        O = f_activacion(h)
        error += (esperados[idx] - O)**2
    return error / 2

print("--- Iniciando entrenamiento Perceptrón Lineal ---")

# Ciclo de entrenamiento
while i < COTA:
    n = random.randint(0, len(entradas)-1)
    ejemplo = entradas[n]

    h = ejemplo @ w
    O = f_activacion(h)
    esperado = esperados[n]

    # Regla de Widrow-Hoff
    del_w = eta * (esperado - O) * ejemplo
    w = w + del_w

    error = calcularError(esperados, entradas, w)

    if error < error_min:
        error_min = error
        w_min = w.copy()

    i += 1

print("Iteraciones ejecutadas: ", i)
print("Mejor error cuadrático (E_min): ", round(error_min, 4))
print("Pesos optimos encontrados: ", np.round(w_min, 4))