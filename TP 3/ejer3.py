import numpy as np
from keras import layers, models
import matplotlib.pyplot as plt
from keras.optimizers import Adam

# conjunto de 16 emojis de 7x5
emojis_hex = np.array([
   [0x00, 0x0a, 0x0a, 0x00, 0x11, 0x0e, 0x00],  # 0: :)  Feliz
   [0x00, 0x0a, 0x00, 0x1f, 0x11, 0x0e, 0x00],  # 1: :D  Muy feliz
   [0x00, 0x0a, 0x0a, 0x00, 0x0e, 0x11, 0x00],  # 2: :(  Triste
   [0x00, 0x0a, 0x0a, 0x00, 0x1f, 0x00, 0x00],  # 3: :|  Serio
   [0x0a, 0x0a, 0x00, 0x0e, 0x11, 0x0e, 0x00],  # 4: :O  Sorprendido
   [0x00, 0x02, 0x1a, 0x00, 0x11, 0x0e, 0x00],  # 5: ;)  Guinio
   [0x11, 0x0a, 0x0a, 0x00, 0x0e, 0x11, 0x00],  # 6: >:( Enojado
   [0x00, 0x0a, 0x02, 0x00, 0x0e, 0x11, 0x00],  # 7: :'( Llorando
   [0x11, 0x0a, 0x11, 0x00, 0x1f, 0x0e, 0x00],  # 8: XD  xd
   [0x00, 0x00, 0x1b, 0x00, 0x0e, 0x00, 0x00],  # 9: -_- Indiferente
   [0x00, 0x1f, 0x1b, 0x00, 0x11, 0x0e, 0x00],  # 10: B) Lentes
   [0x00, 0x0a, 0x0a, 0x00, 0x03, 0x1c, 0x00],  # 11: :/ Confundido
   [0x00, 0x0a, 0x0a, 0x00, 0x04, 0x0e, 0x04],  # 12: :* Beso
   [0x00, 0x0a, 0x15, 0x00, 0x11, 0x0e, 0x00],  # 13: ^^ Ojos felices
   [0x0a, 0x00, 0x0e, 0x11, 0x11, 0x1f, 0x00],  # 14: D: Asustado
   [0x11, 0x0a, 0x0a, 0x00, 0x11, 0x0e, 0x00]   # 15: >:) Travieso
])

etiquetas = [
    ':)', ':D', ':(', ':|', ':O', ';)', '>:(', ":'(",
    'XD', '-_-', 'B)', ':/', ':*', '^^', 'D:', '>:)'
]

# preparacion de datos de entrada (pasamos cada fila a 5 ceros y unos -> vector de 35)
X = []
for emoji in emojis_hex:
    pixeles = []
    for fila in emoji:
        bits_fila = format(fila, '05b')          # 0x0a -> '01010'
        pixeles += [int(b) for b in bits_fila]   # '01010' -> [0, 1, 0, 1, 0]
    X.append(pixeles)
X = np.array(X, dtype='float32')

# visualizamos algunos de los emojis originales de entrenamiento
plt.figure(figsize=(10, 3))
for i in range(8):
    plt.subplot(1, 8, i + 1)
    plt.imshow(X[i].reshape(7, 5), cmap='gray_r')
    plt.title(etiquetas[i])
    plt.axis('off')
plt.suptitle('Muestra de Emojis de Entrenamiento')
plt.tight_layout()
plt.show()

# modelo de autocodificador
# codificador: 35 -> 18 -> 8 -> 2
nodos_entrada = layers.Input(shape=(35,))
x = layers.Dense(18, activation='tanh')(nodos_entrada)
x = layers.Dense(8, activation='tanh')(x)
espacio_latente = layers.Dense(2, activation='linear')(x)

# decodificador: 2 -> 8 -> 18 -> 35
x = layers.Dense(8, activation='tanh')(espacio_latente)
x = layers.Dense(18, activation='tanh')(x)
nodos_salida = layers.Dense(35, activation='sigmoid')(x)

autocodificador = models.Model(inputs=nodos_entrada, outputs=nodos_salida)
autocodificador.compile(optimizer=Adam(learning_rate=0.001), loss='mse')

# entrenamiento del modelo
autocodificador.fit(X, X, epochs=3000, batch_size=16, verbose=0)
predicciones = autocodificador.predict(X, verbose=0)

pixeles_mal = np.sum((predicciones > 0.5) != X, axis=1)
print("Píxeles mal por emoji:", pixeles_mal)

# visualizacion de espacio latente
codificador = models.Model(inputs=nodos_entrada, outputs=espacio_latente)
puntos = codificador.predict(X, verbose=0)

# definimos la nueva entrada en dos dimensiones que no esta en el entrenamiento
x_nuevo = (puntos[0, 0] + puntos[4, 0]) / 2
y_nuevo = (puntos[0, 1] + puntos[4, 1]) / 2
punto_nuevo = np.array([[x_nuevo, y_nuevo]], dtype=np.float32)

plt.figure(figsize=(8, 6))
plt.scatter(puntos[:, 0], puntos[:, 1], color='blue', label='Emojis entrenados (Z)')
for i, texto in enumerate(etiquetas):
    plt.annotate(texto, (puntos[i, 0], puntos[i, 1]), xytext=(5, 5), textcoords='offset points', fontsize=12)

# grafica de nueva coordenada
plt.scatter(x_nuevo, y_nuevo, color='red', marker='X', s=120, label=f'Nueva coordenada ({x_nuevo:.2f}, {y_nuevo:.2f})')
plt.xlabel('X')
plt.ylabel('Y')
plt.title('Espacio latente de Emojis (2D)')
plt.legend()
plt.grid(alpha=0.3)
plt.show()

# generacion del nuevo emoji pasando la coordenada solo por el decodificador
decodificador = models.Model(inputs=espacio_latente, outputs=nodos_salida)
emoji_generado = decodificador.predict(punto_nuevo, verbose=0)[0]

# grafica de la salida continua del decodificador y su version binaria
plt.figure(figsize=(6, 3))

plt.subplot(1, 2, 1)
plt.imshow(emoji_generado.reshape(7, 5), cmap='gray_r')
plt.title('Emoji generado\n(Salida continua sigmoidea)')

plt.subplot(1, 2, 2)
plt.imshow((emoji_generado > 0.5).reshape(7, 5), cmap='gray_r')
plt.title('Emoji generado\n(Binarizado en 0s y 1s)')

plt.tight_layout()
plt.show()