import numpy as np
import random

entradas_crudas = np.loadtxt(r"c:\Users\Lenovo\Documents\UNAHUR\Redes Neuronales\TP1-ej2-Conjunto-entrenamiento.txt")
esperados_crudos = np.loadtxt(r"c:\Users\Lenovo\Documents\UNAHUR\Redes Neuronales\TP1-ej2-Salida-deseada.txt")

# NORMALIZACIÓN MIN-MAX (Crucial para la Sigmoide)
min_y = np.min(esperados_crudos)
max_y = np.max(esperados_crudos)
esperados = (esperados_crudos - min_y) / (max_y - min_y)

# sesgo/umbral (w0)
unos = np.ones((entradas_crudas.shape[0], 1))
entradas = np.hstack((entradas_crudas, unos))

i = 0
w = np.array([0.0, 0.0, 0.0, 0.0])
error_min = float('inf')
w_min = w.copy()
COTA = 50000
eta = 0.05

# 3. Funciones de Activación No Lineal y Derivada
def sigmoide(h):
    # np.clip evita desbordamientos matemáticos (overflow) si h es muy grande
    h_clipped = np.clip(h, -500, 500)
    return 1 / (1 + np.exp(-h_clipped))

def derivada_sigmoide(O):
    return O * (1 - O)

def calcularError(esperados, entradas, pesos):
    error = 0
    for idx in range(len(entradas)):
        h = entradas[idx] @ pesos
        O = sigmoide(h)
        error += (esperados[idx] - O)**2
    return error / 2

print("--- Iniciando entrenamiento Perceptrón No Lineal (Sigmoide) ---")

# Entrenamiento (Regla Delta Generalizada)
while i < COTA:
    n = random.randint(0, len(entradas)-1)
    ejemplo = entradas[n]

    h = ejemplo @ w
    O = sigmoide(h)
    esperado = esperados[n]

    # Se multiplica por la derivada de la activación
    del_w = eta * (esperado - O) * derivada_sigmoide(O) * ejemplo
    w = w + del_w

    error = calcularError(esperados, entradas, w)

    if error < error_min:
        error_min = error
        w_min = w.copy()

    i += 1

print("Iteraciones ejecutadas: ", i)
print("Mejor error cuadrático normalizado (E_min): ", round(error_min, 6))
print("Pesos óptimos encontrados: ", np.round(w_min, 4))