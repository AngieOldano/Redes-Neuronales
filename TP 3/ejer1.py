# Preparación de los datos de entrada
X = []
for caracter in caracteres:
    pixeles = []
    for fila in caracter:
        bits_fila = format(fila, '05b') # pasamos a binario: 0x0a -> 01010
        pixeles += [int(b) for b in bits_fila] #pasamos 01010 -> [0,1,0,1,0]
    X.append(pixeles)
X = np.array(X, dtype='float32') # convertimos a float32 para que Keras lo pueda procesar


# Modelo de autocodificador
# Codificador: 35 -> 18 -> 8 -> 2
nodos_entrada = layers.Input(shape=(35,))
x = layers.Dense(18, activation='tanh')(nodos_entrada)
x = layers.Dense(8, activation='tanh')(x) # tangente porque su salida esta centrada en 0
espacio_latente = layers.Dense(2, activation='linear')(x) # lineal para mejor visualización del espacio latente

#Decodificador: 2 -> 8 -> 18 -> 35
x = layers.Dense(8, activation='tanh')(espacio_latente)
x = layers.Dense(18, activation='tanh')(x)
nodos_salida = layers.Dense(35, activation='sigmoid')(x) # sigmoide para que la salida esté entre 0 y 1, como los datos de entrada

#Creación autocodificador
autocodificador = models.Model(inputs=nodos_entrada, outputs=nodos_salida)
autocodificador.compile(optimizer=Adam(learning_rate=0.001), loss='mse') # 0.001 Es el punto de partida estándar en Keras debido a su tasa de aprendizaje adaptativo


# Entrenamiento del modelo
autocodificador.fit(X, X, epochs=3000, batch_size=32, verbose=0)
predicciones = autocodificador.predict(X,verbose=0)


# Cálculo de errores
errores_mse = np.mean((X - predicciones) ** 2, axis=1)
pixeles_mal = np.sum((predicciones > 0.5) != X, axis=1)


# Visualización del espacio latente
