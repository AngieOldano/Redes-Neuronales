import numpy as np
import random

entradas = np.array([[-1, 1], [1, -1], [-1, -1], [1, 1]])
esperados = np.array([1, 1, -1, -1])

# umbral
unos = np.ones((entradas.shape[0], 1))
entradas = np.hstack((entradas, unos))

# activacion y su derivada
def tanh(h): return np.tanh(h)
def derivada_tanh(o): return 1.0 - o**2

# matriz w (entrada a oculta): 4 neuronas ocultas 3 conexiones de entrada (2 variables + 1 sesgo)
w = np.random.uniform(-0.5, 0.5, (4, 3))
# matriz W (oculta a salida): 1 neurona de salida 5 conexiones (4 ocultas + 1 sesgo)
W = np.random.uniform(-0.5, 0.5, (1, 5))

eta = 0.1
COTA = 10000

print("Entrenando...")
print(f'Matriz w: {w}')
print(f'Matriz W: {W}')
for iteracion in range(COTA):
    n = random.randint(0, len(entradas)-1)
    xi = entradas[n]
    zeta = esperados[n]

    # propagacion hacia adelante
    V_oculta = tanh(w @ xi)
    # se agrega el sesgo a la capa oculta antes de pasar a la capa de salida
    V_oculta_con_sesgo = np.append(V_oculta, 1.0)
    O_salida = tanh(W @ V_oculta_con_sesgo)

    # retropropagacion del error
    delta_salida = (zeta - O_salida) * derivada_tanh(O_salida)
    # retropropagar delta a la capa oculta, se excluye el peso del sesgo
    delta_oculta = derivada_tanh(V_oculta) * (W[:, :-1].T @ delta_salida)
    W += eta * np.outer(delta_salida, V_oculta_con_sesgo)
    w += eta * np.outer(delta_oculta, xi)


print("Prueba de la red entrenada:")
for n in range(len(entradas)):
    xi = entradas[n]
    V_oculta = np.append(tanh(w @ xi), 1.0)
    O_salida = tanh(W @ V_oculta)
    print(f"Entrada: {xi[:2]} -> Esperado: {esperados[n]}, Predicción red: {np.round(O_salida[0], 2)}")